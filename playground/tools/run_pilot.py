#!/usr/bin/env python3
"""Multi-seed, multi-worker pilot runner for ANI-Gamut (P1).

For each (seed, level) cell: redeploy a clean isolated substrate -> apply the dense
brownfield with the target tenant held out -> run the agent -> verify (S = target
solved?, B_frac = collateral damage). Aggregates per level: success-rate and
P(B_frac=0) with Wilson 95% intervals, plus mean steps/tokens (iso-budget cost, H4).

Parallelism (--workers K): K isolated containerlab instances (srv6-w0..srv6-w{K-1},
generated by 26-agai-srv6/deploy/gen-worker-topos.py) run cells concurrently. The
agent phase dominates and is API-latency-bound, so cells overlap well even on few
CPUs. Each worker owns one lab and its own task/result/log files, so rigor is
unchanged: every cell still runs on a fresh redeploy with the baseline guard.

    .venv/bin/python tools/run_pilot.py --n 20 --workers 4 --levels a0,a1,a1plus
Run from the repo root on the VM with the venv (ANTHROPIC_API_KEY in .env).
"""
import argparse
import json
import math
import os
import queue
import subprocess
import sys
import threading
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GEN = str(ROOT / "tools" / "gen_tenants.py")
RUN_START = None
PRINT_LOCK = threading.Lock()
ROWS_LOCK = threading.Lock()
DEPLOY_LOCK = threading.Lock()   # serialize redeploy: the Makefile preflight makes a
                                 # host vrf table 100 that collides across concurrent deploys

# Fault injection hook (the fault-layer branch owns tools/fault_layer.py). Guarded so
# run_pilot works on servizi-srv6 before that module is merged: absent -> a no-op window
# (and lam defaults to 0 = no faults anyway).
try:
    from fault_layer import fault_window            # tools/ is on sys.path when run as a script
except ImportError:
    try:
        from tools.fault_layer import fault_window  # when tools is an importable package
    except ImportError:
        from contextlib import contextmanager

        @contextmanager
        def fault_window(*_a, **_k):
            yield None

# Rough cost estimate for the end-of-run summary. Per-million-token USD rates,
# substring-matched on the model name so dated ids (claude-haiku-4-5-20251001) match.
# No prompt-caching discount is assumed, so the figure is an UPPER bound: the real
# bill is lower whenever cache reads hit. Update the rates if pricing changes.
PRICING_PER_MTOK = {
    "claude-haiku-4-5":  (1.0, 5.0),
    "claude-sonnet-4-5": (3.0, 15.0),
    "claude-opus-4-5":   (5.0, 25.0),
}


def _rate_for(model):
    for k, rate in PRICING_PER_MTOK.items():
        if k in (model or ""):
            return rate
    return None


def _fmt(sec):
    sec = int(sec)
    h, r = divmod(sec, 3600)
    m, s = divmod(r, 60)
    return f"{h}:{m:02d}:{s:02d}" if h else f"{m}:{s:02d}"


def _emit(line):
    with PRINT_LOCK:
        sys.stdout.write(line + "\n")
        sys.stdout.flush()


def _cum():
    return _fmt(time.time() - RUN_START) if RUN_START else "0:00"


def _run(cmd, timeout=900):
    return subprocess.run(cmd, cwd=str(ROOT), capture_output=True, text=True, timeout=timeout)


def _spin(cmd, label, timeout=900, animate=True):
    """Run a subprocess. animate=True -> live single-line indicator (serial only);
    animate=False -> atomic start/done lines, safe under K parallel workers."""
    if not animate:
        _emit(f"  {label} ...")
        t0 = time.time()
        try:
            r = subprocess.run(cmd, cwd=str(ROOT), capture_output=True, text=True, timeout=timeout)
            rc, out, err = r.returncode, r.stdout, r.stderr
        except subprocess.TimeoutExpired as e:
            rc, out, err = 124, (e.stdout or ""), ((e.stderr or "") + " [timeout]")
        _emit(f"  {label} done {_fmt(time.time() - t0)} / {_cum()}")
        return rc, out, err
    p = subprocess.Popen(cmd, cwd=str(ROOT), stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    t0 = time.time()
    i = 0
    while p.poll() is None:
        el = int(time.time() - t0)
        sys.stdout.write(f"\r  {label} ... {el // 60}:{el % 60:02d} {'.' * (1 + i % 3):<3} / {_cum()}  ")
        sys.stdout.flush()
        time.sleep(0.5)
        i += 1
        if time.time() - t0 > timeout:
            p.kill()
            break
    out, err = p.communicate()
    el = int(time.time() - t0)
    sys.stdout.write(f"\r  {label} done {el // 60}:{el % 60:02d} / {_cum()}            \n")
    sys.stdout.flush()
    return p.returncode, out, err


def _gen(common, label, animate, *extra):
    return _spin([sys.executable, GEN, *common, *extra], label, 420, animate)


def wilson(k, n, z=1.96):
    if n == 0:
        return (0.0, 0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (p, max(0.0, c - h), min(1.0, c + h))


def _valid(r):
    return not (r.get("invalid_baseline") or r.get("redeploy_failed")
                or r.get("agent_failed") or r.get("cell_error")
                or r.get("apply_failed"))


def compute_aggregate(rows, levels):
    agg = {}
    for lvl in levels:
        lr = [r for r in rows if r["level"] == lvl and _valid(r)]
        n = len(lr)
        if not n:
            continue
        succ = sum(1 for r in lr if r["solved"])
        db = sum(1 for r in lr if r["damage_free"])
        ps, sl, su = wilson(succ, n)
        pb, bl, bu = wilson(db, n)
        ms = sum(r.get("steps") or 0 for r in lr) / n
        mt = sum(r.get("tokens") or 0 for r in lr) / n
        agg[lvl] = {"n": n, "success": succ, "success_rate": round(ps, 3),
                    "success_ci95": [round(sl, 3), round(su, 3)],
                    "damage_free": db, "p_b0": round(pb, 3),
                    "p_b0_ci95": [round(bl, 3), round(bu, 3)],
                    "mean_steps": round(ms, 1), "mean_tokens": round(mt)}
    return agg


def save_results(path, seeds, levels, args, rows, t0, status):
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(json.dumps({
        "status": status, "seeds": seeds, "levels": levels, "workers": args.workers,
        "model": args.model, "target": args.target, "op": args.op, "lambda": args.lmbda,
        "fault_spec": args.fault_spec,
        "rows": rows, "aggregate": compute_aggregate(rows, levels),
        "elapsed_s": round(time.time() - t0, 1),
    }, indent=2))


def run_cell(w, seed, lvl, a, animate):
    """Run one (seed, level) cell on worker w's isolated lab. Returns the result row."""
    tag = f"w{w} seed={seed} {lvl}"
    lab = f"{a.prefix}-w{w}"
    topo = f"topo-w{w}.yaml"
    cell_res = f"/tmp/pilot_cell_w{w}.json"
    recipe = f"/tmp/pilot_recipe_w{w}.json"   # A3-T: the gen_tenants --emit-provision recipe
    task = str(ROOT / "tasks" / f"target_w{w}.json")
    logs_dir = f"logs/w{w}"
    common = ["--lab", lab, "--overlap-rate", str(a.overlap),
              "--seed", str(seed), "--target", str(a.target), "--op", a.op]
    if a.sizes:                                  # change-set scale: sized multi-homed tenants
        common += ["--sizes", a.sizes, "--topo", f"{a.srv6_repo}/{topo}"]
    else:
        common += ["--tenants", str(a.tenants)]
    if a.hosts_aggregator:
        common += ["--hosts-aggregator", a.hosts_aggregator]

    with DEPLOY_LOCK:
        rc_rd, _, err_rd = _spin(
            ["bash", "-c", f"cd {a.srv6_repo} && sudo make destroy TOPO_FILE={topo} >/dev/null 2>&1; "
             f"sudo make deploy TOPO_FILE={topo}"], f"[{tag}] redeploy", 600, animate)
    if rc_rd != 0:
        _emit(f"  [{tag}] REDEPLOY FAILED rc={rc_rd}: {err_rd[-300:]}")
        return {"seed": seed, "level": lvl, "worker": w, "redeploy_failed": True}

    rc_ap, _, err_ap = _gen(common, f"[{tag}] apply", animate, "--emit-task", task,
                            "--emit-provision", recipe, "--mode", "apply")
    if rc_ap != 0:
        _emit(f"  [{tag}] APPLY FAILED rc={rc_ap}: {err_ap[-300:]}")
        return {"seed": seed, "level": lvl, "worker": w, "apply_failed": True}
    # baseline guard: the held-out brownfield MUST be clean before the agent acts
    _gen(common, f"[{tag}] baseline", animate, "--mode", "verify", "--result", cell_res)
    base = json.loads(Path(cell_res).read_text())
    # The held-out brownfield MUST be clean (not already solved, zero collateral): we measure
    # agent-induced damage against it, so a dirty baseline contaminates B_frac. Skip (never mask).
    if base["solved"] or not base["damage_free"]:
        _emit(f"  [{tag}] BASELINE NOT CLEAN (solved={base['solved']}, b_frac={base['b_frac']}) -> SKIP")
        return {"seed": seed, "level": lvl, "worker": w, "invalid_baseline": True,
                "baseline_b_frac": base["b_frac"]}

    agent = [sys.executable, "-m", "agent.agent_runner", "--lab", lab, "--task", task,
             "--provider", a.provider, "--model", a.model, "--agent-mode", "react",
             "--level", lvl, "--max-steps", str(a.max_steps), "--logs-dir", logs_dir]
    if lvl in ("a1", "a1plus"):
        agent.append("--enable-rollback")
    if lvl == "a3t":
        agent += ["--provision-recipe", recipe]
    # faults injected ONLY around the agent; verify runs after (clean substrate) and measures
    # the RESIDUAL damage the agent left under stress. lambda=0 -> fault_window is a no-op.
    with fault_window(lab, a.lmbda, seed, spec=a.fault_spec):
        rc_ag, _, err_ag = _spin(agent, f"[{tag}] agent {lvl}", 900, animate)
    if rc_ag != 0:
        _emit(f"  [{tag}] AGENT FAILED rc={rc_ag}: {err_ag[-400:]}")
        return {"seed": seed, "level": lvl, "worker": w, "agent_failed": True}

    _gen(common, f"[{tag}] verify", animate, "--mode", "verify", "--result", cell_res)
    m = json.loads(Path(cell_res).read_text())
    steps = tokens = in_tok = out_tok = None
    rr = ROOT / logs_dir / "run_result.json"
    if rr.exists():
        d = json.loads(rr.read_text())
        steps, tokens = d.get("history_length"), d.get("total_tokens")
        in_tok, out_tok = d.get("prompt_tokens"), d.get("completion_tokens")
    _emit(f"  [{tag}] S={m['s_pass']}/{m['s_total']} solved={m['solved']} "
          f"B_frac={m['b_frac']} damage_free={m['damage_free']} steps={steps} tokens={tokens}")
    return {"seed": seed, "level": lvl, "worker": w, **m,
            "steps": steps, "tokens": tokens, "in_tok": in_tok, "out_tok": out_tok}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=5, help="number of seeds")
    ap.add_argument("--base", type=int, default=42, help="first seed")
    ap.add_argument("--levels", default="a0,a1,a1plus")
    ap.add_argument("--target", type=int, default=1)
    ap.add_argument("--tenants", type=int, default=4)
    ap.add_argument("--sizes", default="",
                    help="change-set: comma tenant sizes (e.g. 25,20,15,10); implies the "
                         "multi-homed scale and overrides --tenants")
    ap.add_argument("--hosts", type=int, default=0,
                    help="change-set: regenerate worker topos with N multi-homed hosts (e.g. 75)")
    ap.add_argument("--homing", type=int, default=3,
                    help="change-set: number of PEs each host is wired to")
    ap.add_argument("--overlap", type=float, default=0.5)
    ap.add_argument("--provider", default="anthropic")
    ap.add_argument("--model", default="claude-haiku-4-5-20251001")
    ap.add_argument("--max-steps", dest="max_steps", type=int, default=25)
    ap.add_argument("--op", choices=["onboard", "add-site", "change-set"], default="onboard",
                    help="service operation held out for the target tenant (T1=onboard, T2=add-site)")
    ap.add_argument("--lambda", dest="lmbda", type=float, default=0.0,
                    help="fault intensity in [0,1]; 0 = no faults (baseline). Faults are injected "
                         "around the agent and removed before verify (residual-damage semantics)")
    ap.add_argument("--fault-spec", dest="fault_spec", default="default",
                    choices=["default", "loss", "freeze"], help="fault recipe (fault_layer)")
    ap.add_argument("--workers", type=int, default=1, help="parallel isolated labs (K)")
    ap.add_argument("--prefix", default="srv6", help="lab name prefix -> <prefix>-w<N>")
    # Host aggregation is the DEFAULT (12 host containers -> 1 aggregator, host legs in
    # per-host netns; validated parity with the legacy substrate). --per-host opts out.
    ap.add_argument("--per-host", "--no-aggregate-hosts", dest="per_host", action="store_true",
                    help="legacy substrate: one container per host (opt-out of the default host "
                         "aggregation). Propagated downstream: without this the lab runs aggregated.")
    ap.add_argument("--hosts-node", default="hosts",
                    help="aggregator node name when aggregated, the default (env ANI_HOSTS_AGG)")
    ap.add_argument("--keep-labs", dest="keep_labs", action="store_true",
                    help="do not tear down the worker labs when the campaign finishes")
    ap.add_argument("--out", default=str(ROOT / "results" / "pilot.json"))
    ap.add_argument("--srv6-repo", dest="srv6_repo", default=str(Path.home() / "26-agai-srv6"),
                    help="path to 26-agai-srv6 (clean redeploy + worker topos)")
    a = ap.parse_args()

    # Default = aggregated; --per-host opts out to the legacy one-container-per-host substrate.
    a.hosts_aggregator = "" if a.per_host else a.hosts_node
    # Export to child processes (agent driver reads ANI_HOSTS_AGG; gen_tenants defaults
    # --hosts-aggregator from it; gen-worker-topos gets --aggregate-hosts below).
    if a.hosts_aggregator:
        os.environ["ANI_HOSTS_AGG"] = a.hosts_aggregator

    # Preflight DNS: every cell calls the LLM API; if the VM lost api.anthropic.com
    # resolution (roaming network) the run would burn minutes dying. check_dns.py is
    # fault-owned (guarded: skipped if not yet merged onto this branch). It prints the fix.
    dns = ROOT / "tools" / "check_dns.py"
    if dns.exists() and subprocess.run([sys.executable, str(dns)]).returncode != 0:
        print("PREFLIGHT FAILED: DNS check failed (see above for the fix).")
        return 1

    # Preflight: the agent subprocess runs under THIS interpreter; if launched outside
    # the venv, its deps are missing and every agent run crashes in <1s. Catch it now.
    pf = _run([sys.executable, "-m", "agent.agent_runner", "--help"], 60)
    if pf.returncode != 0:
        print("PREFLIGHT FAILED: the agent is not importable under\n"
              f"  {sys.executable}\n"
              "  Activate the venv (`source .venv/bin/activate`) or launch with\n"
              "  `.venv/bin/python tools/run_pilot.py ...`.\n"
              f"  stderr tail:\n{pf.stderr[-600:]}")
        return 1

    seeds = list(range(a.base, a.base + a.n))
    levels = [x.strip() for x in a.levels.split(",") if x.strip()]
    rows = []
    t0 = time.time()
    global RUN_START
    RUN_START = t0
    animate = a.workers == 1
    print(f"pilot: seeds={seeds} levels={levels} workers={a.workers} "
          f"model={a.model} target=tenant{a.target} op={a.op} lambda={a.lmbda} "
          f"substrate={'per-host' if a.per_host else 'aggregated(' + a.hosts_node + ')'}")
    save_results(a.out, seeds, levels, a, rows, t0, "running")   # clear any stale file

    # Generate K isolated per-worker topologies (name + mgmt distinct, master/rabbit dropped).
    agg_flag = f" --aggregate-hosts --hosts-node {a.hosts_aggregator}" if a.hosts_aggregator else ""
    hosts_flag = f" --hosts {a.hosts} --homing {a.homing}" if a.hosts else ""
    rc_t, _, err_t = _spin(["bash", "-c",
        f"cd {a.srv6_repo} && {sys.executable} deploy/gen-worker-topos.py "
        f"--workers {a.workers} --prefix {a.prefix}{agg_flag}{hosts_flag}"], "gen worker topos", 120, animate)
    if rc_t != 0:
        print(f"FAILED to generate worker topologies: {err_t[-400:]}")
        return 1

    cells = queue.Queue()
    for seed in seeds:
        for lvl in levels:
            cells.put((seed, lvl))

    def worker(w):
        while True:
            try:
                seed, lvl = cells.get_nowait()
            except queue.Empty:
                break
            try:
                row = run_cell(w, seed, lvl, a, animate)
            except Exception as e:
                _emit(f"  [w{w} seed={seed} {lvl}] CELL ERROR: {e}")
                row = {"seed": seed, "level": lvl, "worker": w, "cell_error": str(e)}
            with ROWS_LOCK:
                rows.append(row)
                save_results(a.out, seeds, levels, a, rows, t0, "running")
            cells.task_done()
        # the worker owns lab w: tear it down so containers don't linger after the run
        if not a.keep_labs:
            with DEPLOY_LOCK:
                _spin(["bash", "-c", f"cd {a.srv6_repo} && sudo make destroy TOPO_FILE=topo-w{w}.yaml "
                       ">/dev/null 2>&1; true"], f"[w{w}] teardown", 120, animate)

    threads = [threading.Thread(target=worker, args=(w,), daemon=True) for w in range(a.workers)]
    for th in threads:
        th.start()
    for th in threads:
        th.join()

    agg = compute_aggregate(rows, levels)
    print(f"\n==== AGGREGATE ({len(seeds)} seeds, {a.workers} workers, {round(time.time()-t0)}s) ====")
    print(f"{'level':7} {'success (Wilson95)':24} {'P(B=0) (Wilson95)':24} {'steps':>7} {'tokens':>9}")
    for lvl in levels:
        al = agg.get(lvl)
        if not al:
            continue
        slo, shi = al["success_ci95"]
        blo, bhi = al["p_b0_ci95"]
        print(f"{lvl:7} {al['success']}/{al['n']}={al['success_rate']:.2f} [{slo:.2f},{shi:.2f}]   "
              f"{al['damage_free']}/{al['n']}={al['p_b0']:.2f} [{blo:.2f},{bhi:.2f}]   "
              f"{al['mean_steps']:7.1f} {al['mean_tokens']:9.0f}")

    # Rough token + cost summary (for tracking the Anthropic credit balance).
    valid = [r for r in rows if _valid(r)]
    tot = sum(r.get("tokens") or 0 for r in valid)
    tin = sum(r.get("in_tok") or 0 for r in valid)
    tout = sum(r.get("out_tok") or 0 for r in valid)
    if tot:
        if tin + tout == 0:                  # split unavailable -> assume ~12% output (ReAct: input-heavy)
            tout = int(round(tot * 0.12)); tin = tot - tout
            split = "split stimato ~88/12"
        else:
            split = "split reale (run_result.json)"
        rate = _rate_for(a.model)
        print(f"\n==== COST (rough, upper bound) ====")
        print(f"tokens: total={tot:,}  input={tin:,}  output={tout:,}  "
              f"({len(valid)} celle valide; {split})")
        if rate:
            cost = tin * rate[0] / 1e6 + tout * rate[1] / 1e6
            print(f"est. cost: ${cost:.4f}  @ ${rate[0]:.0f}/${rate[1]:.0f} per MTok "
                  f"({a.model}); no cache discount, real bill <= this")
        else:
            print(f"est. cost: n/d (modello {a.model} non in PRICING_PER_MTOK)")

    save_results(a.out, seeds, levels, a, rows, t0, "complete")
    print(f"\nresults -> {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
